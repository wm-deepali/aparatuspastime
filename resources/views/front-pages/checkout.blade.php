        clearErrors();

       const payload = { payment_method: form.querySelector('input[name="payment_method"]:checked').value };

const formVisible = !newForm.classList.contains('hidden');
const checkedCard = form.querySelector('input[name="address_choice"]:checked');

if (formVisible) {
  Object.assign(payload, newAddressData());      // customer is filling a new address
} else if (checkedCard) {
  payload.address_id = checkedCard.value;        // customer picked a saved address
} else {
  return showErrors('Please select or add a shipping address.');
}

        if (usingNewForm || !selectedAddressId) Object.assign(payload, newAddressData());
        else payload.address_id = selectedAddressId;

        busy(true, 'PLACING ORDER…');
        const r = await post(urls.place, payload);

        if (!r.ok || !r.json.success) {
          busy(false);
          return showErrors(flattenErrors(r.json));
        }

        // Cash on delivery: done
        if (r.json.type === 'cod') {
          window.location.href = r.json.redirect_url;
          return;
        }

        // Razorpay
        const d = r.json;
        const rzp = new Razorpay({
          key: d.key,
          amount: d.amount,
          currency: 'INR',
          name: 'Aparatus Pastime',
          description: 'Order payment',
          order_id: d.razorpay_order_id,
          prefill: { name: d.customer_name, email: d.customer_email, contact: d.customer_phone },
          theme: { color: '#F58220' },
          modal: { ondismiss: () => busy(false) },
          handler: async function (resp) {
            busy(true, 'CONFIRMING PAYMENT…');
            const v = await post(urls.rzpDone, {
              order_id: d.order_id,
              razorpay_payment_id: resp.razorpay_payment_id,
              razorpay_order_id: resp.razorpay_order_id,
              razorpay_signature: resp.razorpay_signature,
            });
            if (v.ok && v.json.success) window.location.href = v.json.redirect_url;
            else { busy(false); showErrors(flattenErrors(v.json)); }
          },
        });
        rzp.on('payment.failed', (resp) => {
          busy(false);
          showErrors(resp.error?.description || 'Payment failed. Please try again.');
        });
        rzp.open();
      });
    })();
