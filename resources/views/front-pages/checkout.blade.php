      const stateSel  = document.getElementById('state-select');
      const citySel   = document.getElementById('city-select');
      const hasSaved  = @json($hasAddresses);

      let selectedAddressId = @json($selectedAddressId);
      let usingNewForm = !hasSaved;

      // ── helpers ──────────────────────────────────────────────
      async function post(url, data) {
        const res = await fetch(url, {
          method: 'POST',
          headers: {
            'Accept': 'application/json',
            'Content-Type': 'application/json',
            'X-CSRF-TOKEN': csrf,
            'X-Requested-With': 'XMLHttpRequest',
          },
          body: JSON.stringify(data),
        });
        let json = {};
        try { json = await res.json(); } catch (e) {}
        return { ok: res.ok, status: res.status, json };
      }

      function showErrors(messages) {
        const list = Array.isArray(messages) ? messages : [messages];
        errBox.innerHTML = list.map(m => `<div><i class="fa-solid fa-circle-exclamation mr-1"></i>${m}</div>`).join('');
        errBox.classList.remove('hidden');
        errBox.scrollIntoView({ behavior: 'smooth', block: 'center' });
      }
      function clearErrors() { errBox.classList.add('hidden'); errBox.innerHTML = ''; }

      function flattenErrors(json) {
        if (json.errors) return Object.values(json.errors).flat();
        return [json.message || 'Something went wrong. Please try again.'];
      }

      function busy(on, label) {
        placeBtn.disabled = on;
        placeLbl.textContent = on ? (label || 'PROCESSING…') : 'COMPLETE & PLACE ORDER';
      }

      function newAddressData() {
        const fd = new FormData(form);
        return {
          name: fd.get('name'), email: fd.get('email'), phone: fd.get('phone'),
          address_line_1: fd.get('address_line_1'), address_line_2: fd.get('address_line_2'),
          state_id: fd.get('state_id'), city_id: fd.get('city_id'), pincode: fd.get('pincode'),
        };
      }

      // ── state → cities ───────────────────────────────────────
      stateSel?.addEventListener('change', async () => {
        citySel.innerHTML = '<option value="">Loading…</option>';
        if (!stateSel.value) { citySel.innerHTML = '<option value="">Select state first</option>'; return; }
        try {
          const res = await fetch(urls.cities + stateSel.value, { headers: { 'Accept': 'application/json' } });
          const cities = await res.json();
          citySel.innerHTML = '<option value="">Select city</option>' +
            cities.map(c => `<option value="${c.id}">${c.name}</option>`).join('');
        } catch (e) {
          citySel.innerHTML = '<option value="">Could not load cities</option>';
        }
      });

      // ── saved address selection ──────────────────────────────
      document.querySelectorAll('[data-address-card]').forEach(card => {
        card.addEventListener('click', async () => {
          const id = Number(card.dataset.id);
          if (id === selectedAddressId && !usingNewForm) return;

          selectedAddressId = id;
          usingNewForm = false;
          newForm.classList.add('hidden');

          card.querySelector('input[name="address_choice"]').checked = true;
          
          document.querySelectorAll('[data-address-card]').forEach(c => {
            c.className = 'block p-3 rounded-2xl border-2 cursor-pointer transition border-brand-border bg-white hover:border-brand-blue';
          });
          card.className = 'block p-3 rounded-2xl border-2 cursor-pointer transition border-brand-blue bg-soft-blue';

          // The default address drives GST, so persist it and reload to refresh totals
          const r = await post(urls.addrDef, { address_id: id });
          if (r.ok) window.location.reload();
          else showErrors(flattenErrors(r.json));
        });
      });

      document.getElementById('toggle-new-address')?.addEventListener('click', () => {
        usingNewForm = true;
        newForm.classList.remove('hidden');
        newForm.scrollIntoView({ behavior: 'smooth', block: 'center' });
      });
      document.getElementById('cancel-new-address')?.addEventListener('click', () => {
        usingNewForm = false;
        newForm.classList.add('hidden');
      });

