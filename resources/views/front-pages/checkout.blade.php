        clearErrors();
        const btn = e.currentTarget;
        btn.disabled = true;
        const r = await post(urls.addrNew, newAddressData());
        btn.disabled = false;
        if (r.ok && r.json.success) window.location.reload();
        else showErrors(flattenErrors(r.json));
      });

      // ── payment card highlight ───────────────────────────────
      document.querySelectorAll('input[name="payment_method"]').forEach(radio => {
        radio.addEventListener('change', () => {
