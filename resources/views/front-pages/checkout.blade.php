    (function () {
      const csrf = document.querySelector('meta[name="csrf-token"]').content;
      const urls = {
        place:   @json(route('checkout.place')),
        rzpDone: @json(route('checkout.razorpay.success')),
        addrNew: @json(route('checkout.address.store')),
        addrDef: @json(route('checkout.address.default')),
        cities:  @json(url('checkout/cities')) + '/',
      };

      const form      = document.getElementById('checkout-form');
      const errBox    = document.getElementById('checkout-errors');
      const placeBtn  = document.getElementById('place-order-btn');
